using System.Buffers.Binary;
using System.Text;
using MimeKit;
using OpenMcdf;
using Serilog;

namespace Msg2EmlConverter;

internal static class MsgAttachmentProperties
{
    private static readonly ILogger logger = Log.ForContext(typeof(MsgAttachmentProperties));

    private const string PropertiesStream = "__properties_version1.0";
    private const uint MimeTag = 0x370E001F;
    private const uint ContentLocationTag = 0x3713001F;
    private const uint TextAttachmentCharsetTag = 0x371B001F;
    private const uint CreationTimeTag = 0x30070040;
    private const uint ModificationTimeTag = 0x30080040;
    private const uint AttachmentFlagsTag = 0x37140003;
    private const uint HiddenTag = 0x7FFE000B;
    private const uint MessageSizeTag = 0x0E080003;

    internal static bool IsInlineResource(MimeEntity part)
    {
        return !part.IsAttachment && (!string.IsNullOrWhiteSpace(part.ContentId) || part.ContentLocation != null);
    }

    internal static void Preserve(Stream content, IReadOnlyList<MimeEntity> attachments)
    {
        // MsgKit does not expose setters for these attachment properties.
        // This pass only edits the container generated by MsgKit, not arbitrary input MSG files.
        logger.Debug("Restoring original metadata for {AttachmentCount} MSG attachments.", attachments.Count);
        using var root = RootStorage.Open(content, StorageModeFlags.LeaveOpen);
        long sizeDifference = 0;
        for (var index = 0; index < attachments.Count; index++)
        {
            var storage = root.OpenStorage($"__attach_version1.0_#{index:X8}");
            using var table = storage.OpenStream(PropertiesStream);
            var oldTableLength = table.Length;
            var reserved = new byte[8];
            table.ReadExactly(reserved);
            var entries = ReadEntries(table);
            var part = attachments[index];

            logger.Debug("Attachment {AttachmentIndex}: MIME type {MimeType}, charset {Charset}, location {ContentLocation}, created {CreationDate}, modified {ModificationDate}.",
                index + 1, part.ContentType.MimeType, part.ContentType.Charset, part.ContentLocation,
                part.ContentDisposition?.CreationDate, part.ContentDisposition?.ModificationDate);
            // The MIME tag stores type/subtype; text charsets have a separate standard MAPI property.
            sizeDifference += SetString(storage, entries, MimeTag, part.ContentType.MimeType);
            if (part.ContentType.MediaType.Equals("text", StringComparison.OrdinalIgnoreCase)
                && !string.IsNullOrWhiteSpace(part.ContentType.Charset))
            {
                sizeDifference += SetString(storage, entries, TextAttachmentCharsetTag, part.ContentType.Charset);
            }
            if (part.ContentLocation != null)
            {
                sizeDifference += SetString(storage, entries, ContentLocationTag, part.ContentLocation.OriginalString);
            }

            SetDate(entries, CreationTimeTag, part.ContentDisposition?.CreationDate);
            SetDate(entries, ModificationTimeTag, part.ContentDisposition?.ModificationDate);
            var flags = entries.TryGetValue(AttachmentFlagsTag, out var flagEntry)
                ? BinaryPrimitives.ReadInt32LittleEndian(flagEntry.AsSpan(8))
                : 0;
            var inline = IsInlineResource(part);
            SetValue(entries, AttachmentFlagsTag, BitConverter.GetBytes(inline ? flags | 4 : flags & ~4));
            SetValue(entries, HiddenTag, BitConverter.GetBytes((short)(inline ? 1 : 0)));

            table.Position = 0;
            table.Write(reserved);
            foreach (var entry in entries.Values)
            {
                table.Write(entry);
            }
            table.SetLength(table.Position);
            sizeDifference += table.Length - oldTableLength;
        }

        // Updating strings and property records changes the size recorded in the message's MAPI properties.
        UpdateMessageSize(root, sizeDifference);
        root.Flush();
        logger.Debug("Attachment metadata written; recorded message size adjusted by {SizeDifference} bytes.", sizeDifference);
    }

    private static Dictionary<uint, byte[]> ReadEntries(Stream table)
    {
        // Each MAPI record contains a tag (4 bytes), flags (4 bytes) and a value or stream length (8 bytes).
        var entries = new Dictionary<uint, byte[]>();
        while (table.Position < table.Length)
        {
            var entry = new byte[16];
            table.ReadExactly(entry);
            entries.Add(BinaryPrimitives.ReadUInt32LittleEndian(entry), entry);
        }
        return entries;
    }

    private static long SetString(OpenMcdf.Storage storage, Dictionary<uint, byte[]> entries, uint tag, string value)
    {
        var name = $"__substg1.0_{tag:X8}";
        using var stream = storage.ContainsEntry(name) ? storage.OpenStream(name) : storage.CreateStream(name);
        var originalLength = stream.Length;
        // PT_UNICODE streams use null-terminated UTF-16LE; the property record stores a byte count.
        var bytes = Encoding.Unicode.GetBytes(value + '\0');
        stream.SetLength(0);
        stream.Write(bytes);
        SetValue(entries, tag, BitConverter.GetBytes(bytes.Length));
        return bytes.Length - originalLength;
    }

    private static void SetDate(Dictionary<uint, byte[]> entries, uint tag, DateTimeOffset? value)
    {
        if (value.HasValue)
        {
            // FILETIME is UTC, so preserve the instant even when the source timestamp has a different offset.
            SetValue(entries, tag, BitConverter.GetBytes(value.Value.UtcDateTime.ToFileTimeUtc()));
        }
        else
        {
            // Do not replace an absent timestamp with the time of conversion.
            entries.Remove(tag);
        }
    }

    private static void SetValue(Dictionary<uint, byte[]> entries, uint tag, ReadOnlySpan<byte> value)
    {
        var entry = new byte[16];
        BinaryPrimitives.WriteUInt32LittleEndian(entry, tag);
        BinaryPrimitives.WriteUInt32LittleEndian(entry.AsSpan(4), 6); // Readable and writable.
        value.CopyTo(entry.AsSpan(8));
        entries[tag] = entry;
    }

    private static void UpdateMessageSize(RootStorage root, long difference)
    {
        using var table = root.OpenStream(PropertiesStream);
        table.Position = 32; // Top-level MSG property tables have a 32-byte header.
        var entries = ReadEntries(table);
        if (entries.TryGetValue(MessageSizeTag, out var sizeEntry))
        {
            var size = BinaryPrimitives.ReadInt32LittleEndian(sizeEntry.AsSpan(8));
            BinaryPrimitives.WriteInt32LittleEndian(sizeEntry.AsSpan(8), checked((int)(size + difference)));
            table.Position = 32;
            foreach (var entry in entries.Values)
            {
                table.Write(entry);
            }
        }
    }
}
